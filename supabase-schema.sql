create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 80),
  created_at timestamptz not null default now()
);

create table if not exists public.trips (
  id bigint generated by default as identity primary key,
  organiser_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 120),
  destination text not null,
  vibe text,
  description text,
  image_url text,
  start_date date not null,
  end_date date not null,
  budget_per_person integer not null check (budget_per_person > 0),
  spots_left integer not null default 1 check (spots_left >= 0),
  cost_breakdown jsonb not null default '{}'::jsonb,
  itinerary jsonb not null default '[]'::jsonb,
  status text not null default 'open' check (status in ('open', 'closed')),
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create table if not exists public.saved_trips (
  user_id uuid not null references auth.users(id) on delete cascade,
  trip_id bigint not null references public.trips(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, trip_id)
);

create table if not exists public.trip_requests (
  trip_id bigint not null references public.trips(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'approved', 'declined')),
  created_at timestamptz not null default now(),
  primary key (trip_id, user_id)
);

alter table public.profiles enable row level security;
alter table public.trips enable row level security;
alter table public.saved_trips enable row level security;
alter table public.trip_requests enable row level security;

create policy "profiles are visible to signed in users" on public.profiles for select to authenticated using (true);
create policy "users manage their profile" on public.profiles for all to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "open trips are visible to signed in users" on public.trips for select to authenticated using (status = 'open' or organiser_id = auth.uid());
create policy "organisers manage their trips" on public.trips for all to authenticated using (organiser_id = auth.uid()) with check (organiser_id = auth.uid());
create policy "users manage their saved trips" on public.saved_trips for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "users create and view their requests" on public.trip_requests for select to authenticated using (user_id = auth.uid() or exists (select 1 from public.trips where trips.id = trip_requests.trip_id and trips.organiser_id = auth.uid()));
create policy "users create their own requests" on public.trip_requests for insert to authenticated with check (user_id = auth.uid());
